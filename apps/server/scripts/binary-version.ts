/**
 * The version baked into the `nightshift` binary.
 *
 * The desktop build reads `NIGHTSHIFT_VERSION` and uses 0.1.0 when that is
 * unset (`apps/desktop/electrobun.config.ts`). The root package.json and
 * the server package.json have no version, so this follows that fallback.
 */
export const DESKTOP_VERSION_FALLBACK = "0.1.0";

export function binaryVersion(
	env: { NIGHTSHIFT_VERSION?: string } = process.env,
): string {
	return env.NIGHTSHIFT_VERSION || DESKTOP_VERSION_FALLBACK;
}

/** Sets the build version unless the operator set one at run time. */
export function versionEnvLine(version: string): string {
	return `process.env.NIGHTSHIFT_VERSION ??= ${JSON.stringify(version)};`;
}

/** Source of the binary entry. The version is set before the CLI loads. */
export function binaryEntrySource(input: {
	version: string;
	imports: readonly string[];
	web: readonly string[];
	migrations: readonly string[];
	cli: string;
}): string {
	return [
		"// Generated by scripts/build-binary.ts.",
		...input.imports,
		versionEnvLine(input.version),
		`const { setEmbedded, main } = await import(${JSON.stringify(input.cli)});`,
		`setEmbedded({ web: { ${input.web.join(", ")} }, migrations: { ${input.migrations.join(", ")} } });`,
		"await main(process.argv.slice(2));",
		"",
	].join("\n");
}
