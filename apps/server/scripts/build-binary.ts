/**
 * Builds `nightshift`, Night Shift in one file per platform: the daemon,
 * its web UI, the database migrations and libsql's native module, in a
 * Bun executable. Nothing to install next to it.
 *
 *   bun scripts/build-binary.ts                 # this computer's platform
 *   bun scripts/build-binary.ts --target all    # linux-x64, linux-arm64, darwin-arm64
 *   bun scripts/build-binary.ts --target linux-x64 --skip-web
 *
 * Out: `dist/bin/nightshift-<target>`. `--skip-web` reuses the web build in
 * `apps/web/dist/client`. libsql's native module of another platform is
 * downloaded from npm once, checked against its published integrity, and
 * kept in `.cache/`.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, rmSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

import { DEFAULT_PORT } from "@nightshift/daemon";
import type { BunPlugin } from "bun";

const TARGETS = {
	"linux-x64": { bun: "bun-linux-x64", libsql: "linux-x64-gnu" },
	"linux-arm64": { bun: "bun-linux-arm64", libsql: "linux-arm64-gnu" },
	"darwin-arm64": { bun: "bun-darwin-arm64", libsql: "darwin-arm64" },
} as const;
type Target = keyof typeof TARGETS;

const server = resolve(import.meta.dir, "..");
const root = resolve(server, "../..");
const webDir = join(root, "apps/web");
const webDist = join(webDir, "dist/client");
const migrationsDir = join(root, "packages/db/src/migrate/migrations");
const shims = join(server, "scripts/shims");
const cache = join(server, ".cache");
const out = join(server, "dist/bin");

function parse(argv: string[]) {
	const args = [...argv];
	let targets: Target[] = [`${process.platform}-${process.arch}` as Target];
	let skipWeb = false;
	while (args.length > 0) {
		const arg = args.shift();
		if (arg === "--skip-web") skipWeb = true;
		else if (arg === "--target") {
			const value = args.shift() ?? "";
			targets =
				value === "all"
					? (Object.keys(TARGETS) as Target[])
					: (value.split(",") as Target[]);
		} else throw new Error(`There is no option ${arg}.`);
	}
	for (const target of targets) {
		if (!(target in TARGETS)) {
			throw new Error(
				`No build for ${target}. Use ${Object.keys(TARGETS).join(", ")} or all.`,
			);
		}
	}
	return { targets, skipWeb };
}

/** Every file under `dir`, as paths relative to it. */
function filesIn(dir: string): string[] {
	return readdirSync(dir, { recursive: true, encoding: "utf8" })
		.filter((path) => statSync(join(dir, path)).isFile())
		.sort();
}

async function buildWeb() {
	console.log("Building the web UI…");
	const build = Bun.spawn(["bun", "run", "build"], {
		cwd: webDir,
		// The address the UI was built for. Night Shift marks the pages it
		// serves, and the UI calls the address it came from instead.
		env: {
			...process.env,
			VITE_SERVER_URL:
				process.env.VITE_SERVER_URL ?? `http://localhost:${DEFAULT_PORT}`,
		},
		stdout: "inherit",
		stderr: "inherit",
	});
	if ((await build.exited) !== 0) throw new Error("The web UI did not build.");
}

/**
 * The entry of the binary: embeds the web UI and the migrations (each file
 * imported as a file), hands them to the CLI, then starts it.
 */
async function writeEntry(): Promise<string> {
	const dir = join(cache, "entry");
	mkdirSync(dir, { recursive: true });
	const lines: string[] = [];
	const web: string[] = [];
	const migrations: string[] = [];
	let n = 0;
	const embed = (file: string) => {
		const name = `f${n++}`;
		lines.push(
			`import ${name} from ${JSON.stringify(file)} with { type: "file" };`,
		);
		return name;
	};
	for (const path of filesIn(webDist)) {
		const name = embed(join(webDist, path));
		web.push(`${JSON.stringify(`/${path.split("\\").join("/")}`)}: ${name}`);
	}
	for (const path of filesIn(migrationsDir)) {
		if (!path.endsWith("migration.sql")) continue;
		const name = embed(join(migrationsDir, path));
		migrations.push(`${JSON.stringify(path.split("\\").join("/"))}: ${name}`);
	}
	const entry = join(dir, "nightshift.ts");
	await Bun.write(
		entry,
		[
			"// Generated by scripts/build-binary.ts.",
			...lines,
			`import { setEmbedded } from ${JSON.stringify(join(server, "src/cli.ts"))};`,
			`setEmbedded({ web: { ${web.join(", ")} }, migrations: { ${migrations.join(", ")} } });`,
			`const { main } = await import(${JSON.stringify(join(server, "src/cli.ts"))});`,
			"await main(process.argv.slice(2));",
			"",
		].join("\n"),
	);
	return entry;
}

/** libsql's version, from the copy `@nightshift/db` resolves. */
function libsqlPackage(): { dir: string; version: string } {
	const pkg = Bun.resolveSync("libsql/package.json", join(root, "packages/db"));
	return { dir: dirname(pkg), version: require(pkg).version as string };
}

/**
 * libsql's native module for a target: the installed one when it is this
 * computer's platform, else the npm package, checked against the
 * registry's integrity and kept in `.cache/`.
 */
async function libsqlNative(target: Target): Promise<string> {
	const libsql = libsqlPackage();
	const pkg = `@libsql/${TARGETS[target].libsql}`;
	try {
		return join(
			dirname(Bun.resolveSync(`${pkg}/package.json`, libsql.dir)),
			"index.node",
		);
	} catch {
		// Not installed: another platform.
	}
	const dir = join(
		cache,
		"libsql",
		`${TARGETS[target].libsql}-${libsql.version}`,
	);
	const file = join(dir, "package", "index.node");
	if (existsSync(file)) return file;

	console.log(`Downloading ${pkg}@${libsql.version}…`);
	const meta = (await (
		await fetch(`https://registry.npmjs.org/${pkg}/${libsql.version}`)
	).json()) as { dist: { tarball: string; integrity: string } };
	const tarball = new Uint8Array(
		await (await fetch(meta.dist.tarball)).arrayBuffer(),
	);
	const [algorithm, expected] = meta.dist.integrity.split("-", 2) as [
		string,
		string,
	];
	const actual = createHash(algorithm).update(tarball).digest("base64");
	if (actual !== expected) {
		throw new Error(`${pkg}@${libsql.version} does not match its integrity.`);
	}
	mkdirSync(dir, { recursive: true });
	const archive = join(dir, "package.tgz");
	await Bun.write(archive, tarball);
	const untar = Bun.spawn(["tar", "-xzf", archive, "-C", dir]);
	if ((await untar.exited) !== 0) throw new Error(`${pkg} did not unpack.`);
	return file;
}

/**
 * The bundle's swaps: varlock's loader for `process.env` (the binary has
 * no varlock CLI and no `.env` files), and libsql's run-time pick of its
 * native module for a fixed path, which the executable then embeds.
 */
function plugins(native: string): BunPlugin[] {
	return [
		{
			name: "varlock-shims",
			setup(build) {
				build.onResolve({ filter: /^varlock\/(auto-load|env)$/ }, (args) => ({
					path: join(
						shims,
						args.path === "varlock/env"
							? "varlock-env.ts"
							: "varlock-auto-load.ts",
					),
				}));
			},
		},
		{
			name: "libsql-native",
			setup(build) {
				build.onLoad(
					{ filter: /[\\/]node_modules[\\/]libsql[\\/]index\.js$/ },
					async ({ path }) => {
						const source = await Bun.file(path).text();
						// libsql's own line. Split, so it is plain text here, not a template.
						const pick = ["return require(`@libsql/$", "{target}`);"].join("");
						if (!source.includes(pick)) {
							throw new Error(
								"libsql changed how it loads its native module: update scripts/build-binary.ts.",
							);
						}
						return {
							contents: source.replace(
								pick,
								`return require(${JSON.stringify(native)});`,
							),
							loader: "js",
						};
					},
				);
			},
		},
	];
}

async function compile(target: Target, entry: string) {
	const native = await libsqlNative(target);
	const outfile = join(out, `nightshift-${target}`);
	console.log(`Compiling ${relative(root, outfile)}…`);
	const result = await Bun.build({
		entrypoints: [entry],
		compile: {
			target: TARGETS[target].bun,
			outfile,
			autoloadDotenv: false,
			autoloadBunfig: false,
		},
		// Names stay, so a stack trace from the binary still reads.
		minify: { whitespace: true, syntax: true, identifiers: false },
		plugins: plugins(native),
		// An optional peer of @tanstack/ai-sandbox, imported only when used.
		external: ["@tanstack/ai-persistence"],
	});
	if (!result.success) {
		for (const log of result.logs) console.error(log);
		throw new Error(`nightshift-${target} did not build.`);
	}
}

const { targets, skipWeb } = parse(process.argv.slice(2));
if (!skipWeb) await buildWeb();
if (!existsSync(join(webDist, "index.html"))) {
	throw new Error("There is no web build. Run without --skip-web.");
}
rmSync(join(cache, "entry"), { recursive: true, force: true });
const entry = await writeEntry();
mkdirSync(out, { recursive: true });
for (const target of targets) await compile(target, entry);
console.log("Done.");
